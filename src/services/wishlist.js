import API from "./api";

//////////////////////////////////////////////////////////////
// ❤️ TOGGLE WISHLIST
//////////////////////////////////////////////////////////////
export const wishlistToggle = async (productId) => {
  const res = await API.post("/wishlist/toggle", {
    productId,
  });
  return res.data;
};

//////////////////////////////////////////////////////////////
// 📦 GET WISHLIST
//////////////////////////////////////////////////////////////
export const getWishlist = async () => {
  const res = await API.get("/wishlist");
  return res.data;
};

//////////////////////////////////////////////////////////////
// 🔍 CHECK WISHLIST
//////////////////////////////////////////////////////////////
export const checkWishlist = async (productId) => {
  const res = await API.get(`/wishlist/check/${productId}`);
  return res.data;
};